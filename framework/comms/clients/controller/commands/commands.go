package commands

import (
	"encoding/json"
	"errors"
	"strings"

	actionmodel "github.com/defos-ai/commander/framework/domain/actions"
	agentmodel "github.com/defos-ai/commander/framework/domain/agents"
	"github.com/defos-ai/commander/framework/domain/operations"
	"github.com/defos-ai/commander/framework/id"
)

type DiscoverActionsCommand struct {
	AgentID string                     `json:"agent_id"`
	Scope   *agentmodel.DiscoveryScope `json:"scope,omitempty"`
}

func (r DiscoverActionsCommand) Validate() error { return validateAgentID(r.AgentID) }

type RunActionCommand struct {
	AgentID string                 `json:"agent_id"`
	Call    actionmodel.ActionCall `json:"call"`
}

func (r RunActionCommand) Validate() error {
	if err := validateAgentID(r.AgentID); err != nil {
		return err
	}
	return r.Call.Validate()
}

type StopAgentCommand struct {
	AgentID string `json:"agent_id"`
}

func (r StopAgentCommand) Validate() error { return validateAgentID(r.AgentID) }

// StartOperationCommand starts a mission with an optional caller-owned operation ID.
// An omitted ID is generated by the runner; supplied IDs use canonical UUID text.
type StartOperationCommand struct {
	OperationID string          `json:"operation_id,omitempty"`
	MissionName string          `json:"mission_name"`
	Input       json.RawMessage `json:"input"`
}

func (r StartOperationCommand) Validate() error {
	if r.OperationID != "" && !id.Valid(r.OperationID) {
		return errors.New("operation_id must be a canonical lowercase UUID")
	}
	if strings.TrimSpace(r.MissionName) == "" {
		return errors.New("mission_name must not be blank")
	}
	return nil
}

type AssignTaskCommand struct {
	OperationID string          `json:"operation_id"`
	ActionName  string          `json:"action_name"`
	Input       json.RawMessage `json:"input,omitempty"`
}

func (r AssignTaskCommand) Validate() error {
	if err := validateOperationID(r.OperationID); err != nil {
		return err
	}
	return (actionmodel.ActionCall{ActionName: r.ActionName, Input: r.Input}).Validate()
}

// ResolveContinuationCommand atomically records a decision and queues its tasks.
// Version prevents two decision makers from resolving the same continuation.
type ResolveContinuationCommand struct {
	OperationID string                   `json:"operation_id"`
	TaskID      string                   `json:"task_id"`
	Version     uint64                   `json:"version"`
	Actions     []actionmodel.NextAction `json:"actions"`
}

func (r ResolveContinuationCommand) Validate() error {
	if err := validateOperationID(r.OperationID); err != nil {
		return err
	}
	if !id.Valid(r.TaskID) || r.Version == 0 || r.Actions == nil {
		return errors.New("task_id, version and explicit actions array are required")
	}
	return actionmodel.ValidateNextActions(r.Actions)
}

type AskQuestionCommand struct {
	TaskID         string   `json:"task_id,omitempty"`
	Version        uint64   `json:"version,omitempty"`
	OperationID    string   `json:"operation_id"`
	Text           string   `json:"text"`
	Options        []string `json:"options,omitempty"`
	TimeoutSeconds int      `json:"timeout_seconds,omitempty"`
}

func (r AskQuestionCommand) Validate() error {
	if (r.TaskID != "" || r.Version != 0) && (!id.Valid(r.TaskID) || r.Version == 0) {
		return errors.New("linked questions require a valid task_id and continuation version")
	}
	if err := validateOperationID(r.OperationID); err != nil {
		return err
	}
	if strings.TrimSpace(r.Text) == "" {
		return errors.New("question text must not be blank")
	}
	if r.TimeoutSeconds < 0 || r.TimeoutSeconds > 86400 {
		return errors.New("timeout_seconds must be between 1 and 86400, or omitted for the default")
	}
	if len(r.Options) > 4 {
		return errors.New("questions support at most four options")
	}
	for _, option := range r.Options {
		if strings.TrimSpace(option) == "" {
			return errors.New("question options must not be blank")
		}
	}
	return nil
}

type AnswerQuestionCommand struct {
	OperationID string                  `json:"operation_id"`
	QuestionID  string                  `json:"question_id"`
	Answer      string                  `json:"answer"`
	AnsweredBy  operations.AnswerOrigin `json:"answered_by"`
}

func (r AnswerQuestionCommand) Validate() error {
	if err := validateOperationID(r.OperationID); err != nil {
		return err
	}
	if !id.Valid(r.QuestionID) {
		return errors.New("question_id must be a canonical lowercase UUID")
	}
	if strings.TrimSpace(r.Answer) == "" {
		return errors.New("answer must not be blank")
	}
	return r.AnsweredBy.Validate()
}

type CompleteOperationCommand struct {
	OperationID string          `json:"operation_id"`
	Output      json.RawMessage `json:"output"`
}

func (r CompleteOperationCommand) Validate() error {
	if err := validateOperationID(r.OperationID); err != nil {
		return err
	}
	if !json.Valid(r.Output) {
		return errors.New("output must be valid JSON")
	}
	return nil
}

type FailOperationCommand struct {
	OperationID string `json:"operation_id"`
	Reason      string `json:"reason"`
}

func (r FailOperationCommand) Validate() error {
	if err := validateOperationID(r.OperationID); err != nil {
		return err
	}
	if strings.TrimSpace(r.Reason) == "" {
		return errors.New("reason must not be blank")
	}
	return nil
}

type CancelOperationCommand struct {
	OperationID string `json:"operation_id"`
}

func (r CancelOperationCommand) Validate() error { return validateOperationID(r.OperationID) }

func validateOperationID(value string) error {
	if !id.Valid(value) {
		return errors.New("operation_id must be a canonical lowercase UUID")
	}
	return nil
}

func validateAgentID(value string) error {
	if !id.ValidAgent(value) {
		return errors.New("invalid agent_id")
	}
	return nil
}
